CREATE TABLE IF NOT EXISTS contact_submissions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  email text NOT NULL CHECK (length(email) BETWEEN 3 AND 254),
  locale text NOT NULL CHECK (locale IN ('en', 'es')),
  message text NOT NULL CHECK (length(message) BETWEEN 5 AND 5000),
  name text NOT NULL CHECK (length(name) BETWEEN 1 AND 120),
  type text NOT NULL CHECK (type IN ('consulting', 'speaking', 'fulltime', 'other'))
);
CREATE INDEX IF NOT EXISTS contact_created_idx ON contact_submissions (created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS contact_email_idx ON contact_submissions (email);
CREATE INDEX IF NOT EXISTS contact_locale_created_idx ON contact_submissions (locale, created_at);
CREATE TABLE IF NOT EXISTS contact_control (
  singleton boolean PRIMARY KEY DEFAULT true CHECK (singleton),
  frozen boolean NOT NULL DEFAULT false
);
INSERT INTO contact_control (singleton) VALUES (true) ON CONFLICT DO NOTHING;
CREATE TABLE IF NOT EXISTS contact_imports (
  source_id bigint PRIMARY KEY REFERENCES contact_submissions(id),
  batch text NOT NULL,
  digest text NOT NULL
);
