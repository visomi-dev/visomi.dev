import { defineConfig, devices } from '@playwright/test';
import { nxE2EPreset } from '@nx/playwright/preset';
import { workspaceRoot } from '@nx/devkit';

const selectedBrowser = process.env['PLAYWRIGHT_BROWSERS'];
const allBrowsers = process.env['PLAYWRIGHT_BROWSERS'] === 'all';
const fixture = (port: number, collector = true) => ({
  command: 'exec node --import tsx tools/testing/browser-server.ts',
  url: `https://127.0.0.1:${port}/api/ready`,
  env: {
    VISOMI_E2E_PORT: String(port),
    VISOMI_E2E_HTTPS: 'true',
    TSX_TSCONFIG_PATH: 'tsconfig.base.json',
    VISOMI_E2E_PRIVATE_COLLECTOR: String(collector),
  },
  ignoreHTTPSErrors: true,
  reuseExistingServer: false,
  gracefulShutdown: { signal: 'SIGTERM' as const, timeout: 60000 },
  timeout: 120000,
  cwd: workspaceRoot,
});

const engines = allBrowsers
  ? [
      { name: 'chromium', device: 'Desktop Chrome', port: 8184 },
      { name: 'firefox', device: 'Desktop Firefox', port: 8185 },
      { name: 'webkit', device: 'Desktop Safari', port: 8186 },
    ]
  : [
      {
        name: selectedBrowser === 'webkit' ? 'webkit' : selectedBrowser === 'firefox' ? 'firefox' : 'chromium',
        device:
          selectedBrowser === 'webkit'
            ? 'Desktop Safari'
            : selectedBrowser === 'firefox'
              ? 'Desktop Firefox'
              : 'Desktop Chrome',
        port: 8184,
      },
    ];
const transport = (port: number) => ({
  baseURL: `https://visomi.dev:${port}`,
  proxy: { server: `http://127.0.0.1:${port + 200}` },
});

export default defineConfig({
  ...nxE2EPreset(__filename, { testDir: './src' }),
  workers: 1,
  use: { ignoreHTTPSErrors: true, trace: 'on-first-retry' },
  // Keep telemetry acceptance independent of traffic generated by the authentication/layout matrix.
  // Every intake retains the unchanged production rate limits.
  // Owner-session and route reviews have separate fixtures to retain production authentication/SSR budgets.
  // Session synchronization has its own fixture per engine so repeated logouts retain the normal auth budget.
  // Visit measurements use an independent fixture so the privacy/owner tests keep the existing request budgets.
  webServer: [
    ...engines.flatMap((engine) => [fixture(engine.port), fixture(engine.port + 20), fixture(engine.port + 30)]),
    fixture(8194),
    fixture(8195, false),
  ],
  projects: engines.flatMap((engine) => [
    {
      name: engine.name,
      testIgnore: [
        '**/telemetry.spec.ts',
        '**/owner-session-review.spec.ts',
        '**/session-sync.spec.ts',
        '**/sign-in-routes.spec.ts',
        '**/visit-analytics.spec.ts',
      ],
      use: { ...devices[engine.device], ...transport(engine.port) },
    },
    {
      name: `${engine.name}-telemetry`,
      testMatch: '**/telemetry.spec.ts',
      use: { ...devices[engine.device], ...transport(8194) },
    },
    {
      name: `${engine.name}-visits`,
      testMatch: '**/visit-analytics.spec.ts',
      use: { ...devices[engine.device], ...transport(8195) },
    },
    {
      name: `${engine.name}-owner-session`,
      testMatch: ['**/owner-session-review.spec.ts', '**/sign-in-routes.spec.ts'],
      use: { ...devices[engine.device], ...transport(engine.port + 20) },
    },
    {
      name: `${engine.name}-session-sync`,
      testMatch: '**/session-sync.spec.ts',
      use: { ...devices[engine.device], ...transport(engine.port + 30) },
    },
  ]),
});
